// Common English words that must never falsely match foreign words via accent stripping
export const ENGLISH_STOPWORDS = new Set([
  "the", "a", "an", "is", "are", "am", "in", "on", "at", "to", "for", "of", "with",
  "and", "or", "tap", "pairs", "matching", "select", "correct", "meaning", "write",
  "this", "that", "these", "those", "sentence", "blank", "word", "fill", "complete"
]);

// Strip diacritics for accent-insensitive lookup fallback
export function stripAccents(str: string): string {
  return str.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase();
}

// Helper to extract words from a challenge for seen-words tracking
export function extractWordsFromChallenge(challenge: any): string[] {
  if (!challenge) return [];
  const words: string[] = [];

  if (challenge.hints) {
    try {
      const parsed = typeof challenge.hints === "string" ? JSON.parse(challenge.hints) : challenge.hints;
      for (const k of Object.keys(parsed)) {
        const cleanK = k.trim().toLowerCase();
        words.push(cleanK);
        const tokens = cleanK.match(/[\p{L}\p{N}]+/gu);
        if (tokens) words.push(...tokens);
      }
    } catch {}
  }

  if (challenge.question) {
    const tokens = challenge.question.toLowerCase().match(/[\p{L}\p{N}]+/gu);
    if (tokens) words.push(...tokens);
  }

  if (challenge.answer) {
    const tokens = challenge.answer.toLowerCase().match(/[\p{L}\p{N}]+/gu);
    if (tokens) words.push(...tokens);
  }

  return words;
}

// Helper to look up hint for word/phrase and identify if it is a new word
export function getHintForWord(
  raw: string,
  hintsJson?: string | null,
  seenWords?: Set<string>
): { hint: string; isNew: boolean } | null {
  if (!raw || typeof raw !== "string") return null;

  let customHints: Record<string, string> = {};
  if (hintsJson) {
    try {
      customHints = JSON.parse(hintsJson);
    } catch {
      // ignore JSON parse errors
    }
  }

  const clean = raw.replace(/[¿?¡!.,":;()]/g, "").trim().toLowerCase();
  if (!clean) return null;
  const cleanNoAccents = stripAccents(clean);

  // If seenWords is provided:
  // A word is considered "seen" if it is in seenWords (or accent-insensitive version is in seenWords).
  // If seenWords is NOT provided: default to isSeen = true (meaning words are not treated as new by default).
  const isSeen = seenWords
    ? seenWords.has(clean) || seenWords.has(cleanNoAccents)
    : true;

  // 1. Check custom hints first (exact match)
  for (const [k, v] of Object.entries(customHints)) {
    if (k.toLowerCase() === clean) {
      return { hint: v, isNew: !isSeen };
    }
  }

  // 2. Check custom hints (accent-insensitive)
  if (!ENGLISH_STOPWORDS.has(cleanNoAccents)) {
    for (const [k, v] of Object.entries(customHints)) {
      if (stripAccents(k) === cleanNoAccents) {
        return { hint: v, isNew: !isSeen };
      }
    }
  }

  // 3. Check global vocabulary hints (exact match)
  if (GLOBAL_VOCAB_HINTS[clean]) {
    return { hint: GLOBAL_VOCAB_HINTS[clean], isNew: false };
  }

  // 4. Check global vocabulary hints (accent-insensitive)
  if (!ENGLISH_STOPWORDS.has(cleanNoAccents)) {
    for (const [k, v] of Object.entries(GLOBAL_VOCAB_HINTS)) {
      if (stripAccents(k) === cleanNoAccents) {
        return { hint: v, isNew: false };
      }
    }
  }

  // 5. Morphological / Root lemmatization fallbacks:
  // French elision prefix fallback (e.g. l'eau -> eau, d'eau -> eau, c'est -> est)
  if ((clean.startsWith("l'") || clean.startsWith("d'") || clean.startsWith("c'") || clean.startsWith("s'") || clean.startsWith("j'")) && clean.length > 2) {
    const stripped = clean.slice(2);
    if (GLOBAL_VOCAB_HINTS[stripped]) {
      return { hint: GLOBAL_VOCAB_HINTS[stripped], isNew: false };
    }
  }
  // Plural Spanish/German (-s, -es)
  if (clean.endsWith("es") && GLOBAL_VOCAB_HINTS[clean.slice(0, -2)]) {
    return { hint: `${GLOBAL_VOCAB_HINTS[clean.slice(0, -2)]} (plural)`, isNew: false };
  }
  if (clean.endsWith("s") && GLOBAL_VOCAB_HINTS[clean.slice(0, -1)]) {
    return { hint: `${GLOBAL_VOCAB_HINTS[clean.slice(0, -1)]} (plural)`, isNew: false };
  }
  // Feminine Spanish adjectives (-a -> -o)
  if (clean.endsWith("a") && GLOBAL_VOCAB_HINTS[clean.slice(0, -1) + "o"]) {
    return { hint: GLOBAL_VOCAB_HINTS[clean.slice(0, -1) + "o"], isNew: false };
  }
  // Japanese particles attached to nouns (e.g. ねこと -> ねこ, みずと -> みず)
  if (clean.endsWith("と") && clean.length > 1 && GLOBAL_VOCAB_HINTS[clean.slice(0, -1)]) {
    return { hint: `${GLOBAL_VOCAB_HINTS[clean.slice(0, -1)]} + and`, isNew: false };
  }
  // Japanese polite お- prefix (e.g. おみず -> みず)
  if (clean.startsWith("お") && clean.length > 1 && GLOBAL_VOCAB_HINTS[clean.slice(1)]) {
    return { hint: GLOBAL_VOCAB_HINTS[clean.slice(1)], isNew: false };
  }

  return null;
}
